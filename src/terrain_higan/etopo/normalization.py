@dataclass(frozen=True)
class UpscaleStats:
    z_level: int
    residual_divisor: float
    downscale_patch_divisor: float
    dataset_sample_count: int | None
    dataset_minimum_value: float | None
    dataset_maximum_value: float | None
    dataset_minimum_raw_residual: float | None
    dataset_maximum_raw_residual: float | None


UPSCALE_STATS = [
    UpscaleStats(z_level, *stat_row)
    for z_level, stat_row in enumerate(UPSCALE_STAT_ROWS)
]


def normalize_residuals(
    residuals: torch.Tensor,
    z_level: int,
    *,
    residual_divisor: float | None = None,
) -> torch.Tensor:
    if residual_divisor is None:
        residual_divisor = UPSCALE_STATS[z_level].residual_divisor
    return torch.asinh(residuals / residual_divisor)


def denormalize_residuals(
    residuals: torch.Tensor,
    z_level: int,
    *,
    residual_scale: float | None = None,
) -> torch.Tensor:
    if residual_scale is None:
        residual_scale = UPSCALE_STATS[z_level].residual_divisor
    # return scaled_sinh(residuals, residual_divisor, SinhGradMode.ASYMMETRIC)
    return torch.sinh(residuals) * residual_scale


def normalize_downscaled_patches(
    downsampled_patches: torch.Tensor,
    z_level: int,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Asinh-normalize mean-subtracted downsampled patch values."""
    divisor = UPSCALE_STATS[z_level].downscale_patch_divisor
    patch_means = downsampled_patches.mean(dim=(2, 3), keepdim=True)
    normalized_patches = torch.asinh((downsampled_patches - patch_means) / divisor)
    return normalized_patches, patch_means


def apply_sin_cos_filters_at_frequencies(
    values: torch.Tensor,
    frequencies: tuple[float, ...],
) -> torch.Tensor:
    """Return sin/cos features for each frequency in the supplied order."""
    features = []
    for frequency in frequencies:
        phase = frequency * 2.0 * torch.pi * values
        features.extend((torch.sin(phase), torch.cos(phase)))
    return torch.cat(features, dim=1)

