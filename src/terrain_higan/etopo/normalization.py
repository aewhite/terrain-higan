@torch.no_grad()
def make_normal_knots(
    samples: torch.Tensor,
    num_knots: int,
    z_min: float = -5.0,
    z_max: float = 5.0,
) -> torch.Tensor:
    """
    Build a piecewise-linear mapping from an arbitrary empirical distribution
    to an approximately standard-normal distribution.

    Args:
        samples:
            Tensor containing N samples. May have any shape; it is flattened.
        num_knots:
            Number of interpolation knots.
        z_min:
            Minimum normalized output value.
        z_max:
            Maximum normalized output value.

    Returns:
        knots:
            Tensor of shape [num_knots, 2].

            knots[:, 0] = source-space x values
            knots[:, 1] = corresponding normal-space z values
    """
    if num_knots < 2:
        raise ValueError("num_knots must be >= 2")

    samples = samples.flatten()

    if not samples.is_floating_point():
        samples = samples.float()

    # Uniform spacing in the space the neural network will see.
    z = torch.linspace(
        z_min,
        z_max,
        num_knots,
        device=samples.device,
        dtype=samples.dtype,
    )

    # Convert standard-normal positions to probabilities.
    # ndtr(z) = standard normal CDF.
    p = torch.special.ndtr(z)

    # Find the corresponding empirical source values.
    x = torch.quantile(
        samples,
        p,
        interpolation="linear",
    )

    return torch.stack((x, z), dim=-1)


def normal_from_knots(
    x: torch.Tensor,
    knots: torch.Tensor,
) -> torch.Tensor:
    """
    Map raw values into approximately standard-normal space using
    piecewise-linear interpolation.

    Values outside the knot range are clamped to the endpoint z values.

    Args:
        x:
            Raw input tensor of arbitrary shape.

        knots:
            [S, 2] tensor returned by make_normal_knots().

    Returns:
        Tensor with the same shape as x.
    """
    x_knots = knots[:, 0]
    z_knots = knots[:, 1]

    # Find the upper bounding knot for every x.
    i1 = torch.searchsorted(x_knots, x)

    # Clamp so every point has both a lower and upper knot.
    i1 = i1.clamp(1, x_knots.numel() - 1)
    i0 = i1 - 1

    x0 = x_knots[i0]
    x1 = x_knots[i1]

    z0 = z_knots[i0]
    z1 = z_knots[i1]

    # Linear interpolation.
    #
    # clamp_min handles the rare case where adjacent empirical
    # quantiles have identical values.
    denominator = (x1 - x0).clamp_min(
        torch.finfo(x_knots.dtype).eps
    )

    t = (x - x0) / denominator

    z = z0 + t * (z1 - z0)

    # Saturate values outside the represented empirical range.
    return z.clamp(z_knots[0], z_knots[-1])
