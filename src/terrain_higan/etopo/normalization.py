def normalize_elevation(values: ElevationValues) -> ElevationValues:
    """Normalize raw elevation values expressed in meters."""
    mean_m, std_m = _parameters()
    return (values - mean_m) / std_m


def denormalize_elevation(values: ElevationValues) -> ElevationValues:
    """Convert universal normalized elevation values back to raw meters."""
    mean_m, std_m = _parameters()
    return values * std_m + mean_m


def _parameters() -> tuple[float, float]:
    return ELEVATION_MEAN_M, ELEVATION_STD_M


def scale_patch_deviations(patches: torch.Tensor, scale: float) -> torch.Tensor:
    """Scale each normalized patch's std while preserving its mean."""
    patch_means = patches.mean(dim=(1, 2, 3), keepdim=True)
    return patch_means + (patches - patch_means) * scale


